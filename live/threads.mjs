// Swarm Discussion Curator: turns the team chat into topic threads and a "what the swarm decided" list.
//   node live/threads.mjs   regenerates live/threads.json and live/decisions.md from channel.jsonl
//   in a page: <div id="threads"></div> + <script type="module" src="threads.mjs"> draws the panel and refreshes it
// Both paths use the same buildModel(), so the panel and the files always agree. Classification is keyword-based
// on purpose: every item keeps its chat message number (#n), so anyone can check it against the chat.

const CHAT_URL = "/preview/rts/channel.jsonl";
const REFRESH_MS = 10000;
const SHOWN = 240; // characters of a message shown in the panel

// Topic threads. A message goes to the first topic whose pattern matches, so specific topics come first.
export const TOPICS = [
  { id: "movement", title: "Movement and blocked Workers", re: /movement|\bpaths?\b|freez|froze|blocked|detour|crowd/i },
  { id: "assets", title: "Assets, art and sound downloads", re: /assets?\b|licen[cs]e|kenney|CC0|sounds?\b|audio|\.ogg|manifest/i },
  { id: "economy", title: "Economy: gathering, building, training", re: /economy|gather|shards?\b|mining|\bmine\b|deliver|train/i },
  { id: "combat", title: "Combat and units", re: /combat|damage|\brange\b|brute|grunt|lancer|turret|\bhit/i },
  { id: "referee", title: "Referee, sandbox and players", re: /referee|sandbox|worker thread|forfeit|player/i },
  { id: "replay", title: "Logs and replay", re: /\blogs?\b|replay|validat|tick entr/i },
  { id: "live-tv", title: "Live TV screen", re: /\blive\b|\btv\b|scene|canvas|playlist/i },
  { id: "viewer", title: "2D viewer: art, effects and HUD", re: /\bart\b|sprite|\bfx\b|effects?\b|\bhud\b|minimap|drawTerrain|viewer/i },
  { id: "3d", title: "3D build, scope and roles", re: /\b3d\b|three|roster|\broles?\b|design|terrain|scope/i },
  { id: "tests", title: "Tests and smoke runs", re: /tests?\b|smoke|passing|\bpass\b/i },
];
const GENERAL = { id: "general", title: "General and coordination" };

// "AGREE" counts only as a sign-off: at the start of a message or sentence, or after "I", "we" or "all".
// Mentions like "post AGREE", "before I say AGREE" or "settle it with AGREE" are requests, not agreements.
const AGREE_WORD = /\bAGREE\b/g;
const AGREE_START = /(^|[.!?;]\s*|\b(I|we|all)\s+)$/;
const DECISION_RE = /(\bDecision:|\bdecided (to|on)\b|\bsettled\b|\bgoing with\b|\bfinal call\b|\bwe agreed\b)/i;
const DISAGREE_RE = /\b(disagree|push back|not convinced|I'd rather|instead of|concern)\b/i;

// Turns the raw jsonl text into messages numbered from 0, the same numbering read.mjs uses.
export function parseChat(text) {
  return String(text ?? "")
    .split("\n")
    .filter(Boolean)
    .map((line) => { try { return JSON.parse(line); } catch { return null; } })
    .filter(Boolean)
    .map((m, n) => ({ n, t: String(m.t ?? ""), from: String(m.from ?? "?"), text: String(m.text ?? "") }));
}

export function kindOf(text) {
  if (AGREE_RE.test(text)) return "agree";
  if (DECISION_RE.test(text)) return "decision";
  if (DISAGREE_RE.test(text)) return "disagreement";
  return "status";
}

export function topicOf(text) {
  const hit = TOPICS.find((tp) => tp.re.test(text));
  return hit ? hit.id : GENERAL.id;
}

// A question counts as answered only if a later message from someone else names the asker. That is a heuristic:
// a reply that doesn't use the name shows up as open until someone names the asker.
function answered(items, q) {
  const name = new RegExp(`\\b${q.from}\\b`, "i");
  return items.some((m) => m.n > q.n && m.from !== q.from && name.test(m.text));
}

export function buildModel(messages) {
  const items = messages.map((m) => {
    const text = m.text.replace(/\s+/g, " ").trim();
    return { n: m.n, time: m.t.slice(11, 19), from: m.from, text, kind: kindOf(text), topic: topicOf(text), question: text.includes("?") };
  });
  for (const it of items) if (it.question) it.answered = answered(items, it);

  const topics = [...TOPICS, GENERAL].map((tp) => {
    const msgs = items.filter((i) => i.topic === tp.id);
    return { id: tp.id, title: tp.title, count: msgs.length, last: msgs.at(-1)?.n ?? null, messages: msgs };
  }).filter((tp) => tp.count > 0);

  return {
    generated: new Date().toISOString(),
    messageCount: items.length,
    agrees: items.filter((i) => i.kind === "agree"),
    decisions: items.filter((i) => i.kind === "decision"),
    disagreements: items.filter((i) => i.kind === "disagreement"),
    openQuestions: items.filter((i) => i.question && !i.answered),
    answeredQuestions: items.filter((i) => i.question && i.answered),
    topics,
  };
}

const line = (i) => `- #${i.n} [${i.time}] ${i.from}: ${i.text}`;

export function toMarkdown(model) {
  const out = [
    "# What the swarm decided",
    "",
    `_Generated by live/threads.mjs from channel.jsonl: ${model.messageCount} messages at ${model.generated}._`,
    "_Every item quotes its chat message (#n). Items come from keywords (AGREE, decided, settled, disagree, questions), so a missing item means the chat did not say it in those words. Questions count as answered only when a later message from someone else names the asker._",
    "",
    `## AGREE (${model.agrees.length})`,
    ...(model.agrees.length ? model.agrees.map(line) : ["- none yet"]),
    "",
    `## Decisions (${model.decisions.length})`,
    ...(model.decisions.length ? model.decisions.map(line) : ["- none yet"]),
    "",
    `## Open questions (${model.openQuestions.length})`,
    ...(model.openQuestions.length ? model.openQuestions.map(line) : ["- none open"]),
    "",
    `## Disagreements (${model.disagreements.length})`,
    ...(model.disagreements.length ? model.disagreements.map(line) : ["- none yet"]),
    "",
    "## Threads",
    ...model.topics.map((tp) => `- ${tp.title}: ${tp.count} messages, latest #${tp.last}`),
    "",
  ];
  return out.join("\n");
}

// ---- Node: regenerate the two files -------------------------------------------------------------------------------
if (typeof window === "undefined" && process.argv[1] && process.argv[1].endsWith("threads.mjs")) {
  const fs = await import("node:fs");
  const { fileURLToPath } = await import("node:url");
  const here = new URL(".", import.meta.url);
  const chat = fs.readFileSync(fileURLToPath(new URL("../channel.jsonl", import.meta.url)), "utf8");
  const model = buildModel(parseChat(chat));
  fs.writeFileSync(fileURLToPath(new URL("threads.json", here)), JSON.stringify(model, null, 2) + "\n");
  fs.writeFileSync(fileURLToPath(new URL("decisions.md", here)), toMarkdown(model));
  console.log(`threads: ${model.messageCount} messages, ${model.topics.length} threads, ${model.agrees.length} AGREE, ${model.decisions.length} decisions, ${model.openQuestions.length} open questions`);
}

// ---- Browser: draw the panel ----------------------------------------------------------------------------------------
// All chat text goes in with textContent, never innerHTML, because the chat is untrusted text.
const STYLE = `
.thr{font:14px/1.35 system-ui,sans-serif;color:#d8e6f0;background:#0b1620;padding:12px 14px;border-radius:8px;overflow:hidden}
.thr h2{font-size:16px;margin:0 0 8px;color:#fff}
.thr h3{font-size:12px;letter-spacing:.06em;text-transform:uppercase;color:#7fb8d8;margin:12px 0 4px}
.thr .row{margin:2px 0;white-space:nowrap;overflow:hidden;text-overflow:ellipsis}
.thr .from{color:#f2c46d;font-weight:600}
.thr .num{color:#6c8797}
.thr .agree .from{color:#7ee08a}
.thr .dis .from{color:#ff8a8a}
.thr .muted{color:#6c8797}
`;

function el(tag, cls, text) {
  const e = document.createElement(tag);
  if (cls) e.className = cls;
  if (text !== undefined) e.textContent = text;
  return e;
}

function shortLine(i, cls = "") {
  const row = el("div", `row ${cls}`);
  row.append(el("span", "num", `#${i.n} `), el("span", "from", `${i.from}: `));
  const body = i.text.length > SHOWN ? i.text.slice(0, SHOWN - 1) + "…" : i.text;
  row.append(document.createTextNode(body));
  return row;
}

function section(title, rows, empty, cls) {
  const wrap = el("div", cls);
  wrap.append(el("h3", "", `${title} (${rows.length})`));
  if (!rows.length) wrap.append(el("div", "muted", empty));
  for (const r of rows.slice(-6)) wrap.append(shortLine(r));
  return wrap;
}

export function renderPanel(root, model) {
  root.replaceChildren();
  root.className = "thr";
  root.append(el("h2", "", "What the swarm decided"));
  root.append(el("div", "muted", `${model.messageCount} chat messages · updated ${model.generated.slice(11, 19)} UTC`));
  root.append(section("AGREE", model.agrees, "No AGREE yet.", "agree"));
  root.append(section("Decisions", model.decisions, "No decisions named yet.", ""));
  root.append(section("Open questions", model.openQuestions, "None open.", ""));
  root.append(section("Disagreements", model.disagreements, "None yet.", "dis"));
  const threads = el("div", "");
  threads.append(el("h3", "", "Threads"));
  for (const tp of model.topics) {
    const last = tp.messages.at(-1);
    threads.append(el("div", "row", `${tp.title} · ${tp.count} msgs`));
    if (last) threads.append(shortLine(last, "muted"));
  }
  root.append(threads);
}

if (typeof window !== "undefined" && typeof document !== "undefined") {
  const target = document.getElementById("threads");
  if (target) {
    if (!document.getElementById("thr-style")) {
      const style = el("style");
      style.id = "thr-style";
      style.textContent = STYLE;
      document.head.append(style);
    }
    const load = async () => {
      try {
        const res = await fetch(CHAT_URL, { cache: "no-store" });
        if (!res.ok) throw new Error(`chat ${res.status}`);
        renderPanel(target, buildModel(parseChat(await res.text())));
      } catch (err) {
        target.textContent = `Threads unavailable: ${err.message}`;
      }
    };
    load();
    setInterval(load, REFRESH_MS);
  }
}
